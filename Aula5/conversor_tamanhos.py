#converter metros para centimetros e milimetros
#1m = 100cm, 1m = 1000mm

print("Conversor de metros")
tamanho_metros = float(input("Digite um tamanho em metros: "))
metros_para_cm = tamanho_metros * 100
metros_para_mm = tamanho_metros * 1000
print(f"Valor de {tamanho_metros} em centímetros: {metros_para_cm}cm")
print(f"Valor de {tamanho_metros} em milímetros: {metros_para_mm}mm")

